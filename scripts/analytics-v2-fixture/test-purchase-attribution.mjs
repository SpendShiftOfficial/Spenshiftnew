import assert from 'node:assert/strict';
import {purchaseAttributionEnabled,schemaReady,landingLabels,checkoutLabels,parseLabels,parseContext,validatedReport,NOTICE,MAX_AGE_MS} from '../../lib/analytics-v2/purchase-attribution.mjs';
import {renderDashboard} from '../../lib/analytics-v2/dashboard.mjs';
const origin='https://www.spendshift.com.au';
const paid='?utm_source=instagram&utm_medium=paid_social&utm_campaign=meta_founder_v1&utm_content=creative_01';
const labels={source:'instagram',campaign:'meta_founder_v1',creative:'creative_01'};
assert.deepEqual(landingLabels('',origin,paid),labels);
assert.deepEqual(landingLabels('',origin,paid.replace('instagram','fb').replace('creative_01','creative_08')),{source:'facebook',campaign:'meta_founder_v1',creative:'creative_08'});
assert.deepEqual(landingLabels('https://l.instagram.com/',origin,'?utm_source=instagram&utm_medium=organic_social'),{source:'instagram',campaign:'none_or_unknown',creative:'none_or_unknown'});
assert.equal(landingLabels('',origin,''),null);
assert.equal(landingLabels(origin+'/pricing',origin,paid),null);
assert.equal(landingLabels('',origin,paid+'&utm_source=facebook'),null);
assert.deepEqual(landingLabels('',origin,paid+'&utm_content=creative_02'),{...labels,creative:'none_or_unknown'});
assert.deepEqual(landingLabels('',origin,paid.replace('creative_01','customer%40example.invalid')),{...labels,creative:'none_or_unknown'});
assert.deepEqual(landingLabels('',origin,paid.replace('paid_social','organic_social')),{source:'instagram',campaign:'none_or_unknown',creative:'none_or_unknown'});
assert.equal(parseLabels({...labels,extra:'no'}),null);
assert.equal(parseLabels({...labels,source:'google'}),null);
assert.equal(parseLabels({...labels,campaign:'none_or_unknown'}),null);
assert.deepEqual(checkoutLabels({...labels,notice:NOTICE}),labels);
assert.equal(checkoutLabels(labels),null);
assert.equal(checkoutLabels({...labels,notice:NOTICE,click_id:'synthetic'}),null);
assert.equal(parseContext(JSON.stringify({labels,captured:1}),MAX_AGE_MS+2),null);
assert.equal(parseContext(JSON.stringify({labels,captured:100}),99),null);
assert.deepEqual(parseContext(JSON.stringify({labels,captured:100}),101),labels);
const e={VERCEL:'1',VERCEL_ENV:'production',NEXT_PUBLIC_SITE_URL:origin,SPENDSHIFT_ANALYTICS_V2_SCHEMA_READY:'true',SPENDSHIFT_ANALYTICS_V2_PRIVACY_ENABLED:'true',SPENDSHIFT_ANALYTICS_V2_WAF_REVIEWED:'true',SPENDSHIFT_ANALYTICS_V2_COLLECTION_ENABLED:'true',SPENDSHIFT_ANALYTICS_V2_DASHBOARD_ENABLED:'true',SPENDSHIFT_ANALYTICS_V2_NOTICE_VERSION:'2026-11-v2',SPENDSHIFT_PURCHASE_ATTRIBUTION_SCHEMA_READY:'true',SPENDSHIFT_PURCHASE_ATTRIBUTION_ENABLED:'true'};
assert.equal(purchaseAttributionEnabled(e),false,'hard production gate');
assert.equal(purchaseAttributionEnabled(e,true),true);
assert.equal(purchaseAttributionEnabled({...e,VERCEL_ENV:'preview'},true),false);
assert.equal(purchaseAttributionEnabled({...e,SPENDSHIFT_PURCHASE_ATTRIBUTION_SCHEMA_READY:'false'},true),false);
assert.equal(purchaseAttributionEnabled({...e,SPENDSHIFT_ANALYTICS_V2_COLLECTION_ENABLED:'false'},true),false);
assert.equal(schemaReady({...e,SPENDSHIFT_ANALYTICS_V2_DASHBOARD_ENABLED:'false'}),true,'retention survives disabling reads');
const report={total_orders:3,attributed:1,unattributed:2,groups:[{...labels,count:1}]};
assert.deepEqual(validatedReport(report),report);
assert.equal(validatedReport({...report,attributed:2}),null);
assert.equal(validatedReport({...report,groups:[{...labels,count:1,checkout_hash:'x'}]}),null);
assert.equal(validatedReport({...report,groups:[{...labels,count:1},{...labels,count:1}]}),null);
const html=renderDashboard([],'today',{from:'2026-11-28',to:'2026-11-28'},null,false,report);
assert.match(html,/Purchase attribution/);assert.match(html,/creative_01/);
assert.doesNotMatch(renderDashboard([],'today',{from:'2026-11-28',to:'2026-11-28'},null,false),/Purchase attribution/);
console.log('PASS bounded source/campaign/creative labels, consent marker, expiry, production gates and aggregate validation');
